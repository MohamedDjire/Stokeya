/**
 * Traduit une phrase FR source vers la langue active.
 * À utiliser sur tout texte affiché (titres, boutons, labels…).
 */
export function tr(text: string | null | undefined): string {
  if (text == null || text === '') return text ?? '';
  const lang = getLocaleRuntime().language as AppLanguage;
  if (lang === 'fr') return text;

  const dict = PHRASES[lang === 'ar' ? 'ar' : 'en'];
  let out: string;
  if (dict[text]) {
    out = dict[text];
  } else {
    out = text;
    let matched = false;
    for (const p of PATTERNS) {
      const m = text.match(p.re);
      if (m) {
        const args = m as unknown as string[];
        out = lang === 'ar' ? p.ar(...args) : p.en(...args);
        matched = true;
        break;
      }
    }
    if (!matched) {
      const keys = Object.keys(dict).sort((a, b) => b.length - a.length);
      for (const k of keys) {
        if (k.length < 4) continue;
        if (out.includes(k)) out = out.split(k).join(dict[k]);
      }
    }
  }

  // Chiffres arabes orientaux pour toute chaîne affichée en arabe
  if (lang === 'ar') {
    out = toLocalizedDigits(out, 'ar');
  }
  return out;
}
